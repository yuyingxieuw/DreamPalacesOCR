#!/usr/bin/env python3

import io
import os
import json
from pathlib import Path
from typing import Iterable, List, Dict, Optional
from google.oauth2 import service_account
from googleapiclient.discovery import build
from googleapiclient.http import MediaIoBaseDownload

DRIVE_FOLDER_ID = "1Y79RtyREcbKKLma7jf9NHLGyf-886Pwn"
SERVICE_ACCOUNT_FILE = "/gpfs/scrubbed/yxie993/google_api.json"
PDF_DIR = Path("/gpfs/scrubbed/yxie993/pdfs")
PDF_DIR.mkdir(parents=True, exist_ok=True)
LOG_FAIL = Path("/gpfs/scrubbed/yxie993/download_failures.log")
MAX_FILES = None
MANIFEST = Path("/gpfs/scrubbed/yxie993/manifest.jsonl")

SCOPES = ["https://www.googleapis.com/auth/drive.readonly"]


def get_service():
    """
    connect to service
    """
    creds = service_account.Credentials.from_service_account_file(
        SERVICE_ACCOUNT_FILE, scopes=SCOPES)
    return build("drive", "v3", credentials=creds)


# Recursively scan each folder and collects all PDF files as a flat list
def iter_drive_children(folder_id: str) -> Iterable[dict]:
  page_token = None
  while True:
    resp = drive.files().list(
        q = f"'{folder_id}' in parents and trashed=false",
        fields ="nextPageToken, files(id, name, mimeType)",
        pageSize = 1000,
        pageToken = page_token,
        supportsAllDrives = True,
        includeItemsFromAllDrives = True,
    ).execute()

    for item in resp.get("files", []):
      yield item

    page_token = resp.get("nextPageToken")
    if not page_token:
      break


def walk_drive(folder_id: str, path_parts: Optional[List[str]] = None, records: Optional[List[dict]] = None):
  """Recursively collect PDF files and their folder paths."""
  if path_parts is None:
    path_parts = []
  if records is None:
    records = []

  # new: max_files limiting amount to collect
  if MAX_FILES is not None and len(records) >= MAX_FILES:
    return records

  for item in iter_drive_children(folder_id):
    if MAX_FILES is not None and len(records) >= MAX_FILES:
      break

    mime = item["mimeType"]

    if mime == "application/vnd.google-apps.folder":
      print(f"enter folder: {'/'.join(path_parts + [item['name']])}")
      walk_drive(item["id"], path_parts + [item["name"]], records)
    elif mime == "application/pdf":
      records.append(
          {"file_id": item["id"], "filename": item["name"], "path_parts": path_parts.copy(),}
      )
  print(f"  has collected {len(records)} folder")
  return records


######### wrapper function: collection all pdf id, name, and path
def collect_drive_pdfs(folder_id: str) -> List[Dict]:
  """
  Collect PDF records recursively from Google Drive.
  Return: a list of file record
  """
  records = walk_drive(folder_id)

  print(f"Found {len(records)} PDF files.")
  return records


def download_one(drive, file_id, filename):
  """
  func to download one file
  """
  local_path = PDF_DIR / f"{file_id}.pdf"
  if local_path.exists():
    return "skip"
  try:
    request = drive.files().get_media(fileId=file_id, supportsAllDrives=True)
    fh = io.BytesIO()
    downloader = MediaIoBaseDownload(fh, request)
    done = False
    while not done:
      _, done = downloader.next_chunk()
    local_path.write_bytes(fh.getvalue())
    return "ok"
  except Exception as e:
    with open(LOG_FAIL, "a") as f:
      f.write(f"{file_id}\t{filename}\t{e}\n")
    return "fail"


def main():
    global drive
    drive = get_service()
    print("Connected to Drive")

    records = collect_drive_pdfs(DRIVE_FOLDER_ID)
    print (f'We have {len(records)} file waiting to download')

    #for OCR usage
    with open(MANIFEST, "w", encoding="utf-8") as f:
      for r in records:
          f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"Manifest saved: {len(records)} records -> {MANIFEST}")

    ok = skip = fail = 0
    for i, r in enumerate(records):
        status = download_one(drive, r["file_id"], r["filename"])
        if status == "ok": ok += 1
        elif status == "skip": skip += 1
        else: fail += 1
        if (i+1) % 100 == 0:        #
            print(f"{i+1}/{len(records)} | download {ok} skip {skip} fail {fail}")
    print(f"finish:download {ok},skip {skip},fail {fail}")

if __name__ == "__main__":
    main()
